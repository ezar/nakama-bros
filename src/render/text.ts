export interface TextOptions {
  color?: string
  align?: 'left' | 'center' | 'right'
  /** Draw a 1px offset shadow in this colour. */
  shadow?: string | null
  /** Integer pixel scale. */
  scale?: number
  /** Extra spacing between glyphs. */
  tracking?: number
}

export function textWidth(text: string, scale = 1, tracking = 1): number {
  return text.length * (5 + tracking) * scale - tracking * scale
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  opts: TextOptions = {},
): void {
  const scale = opts.scale ?? 1
  const tracking = opts.tracking ?? 1
  const upper = text.toUpperCase()
  const w = textWidth(upper, scale, tracking)
  let ox = x
  if (opts.align === 'center') ox = x - w / 2
  else if (opts.align === 'right') ox = x - w

  const render = (color: string, dx: number, dy: number) => {
    ctx.fillStyle = color
    let cx = Math.round(ox + dx)
    for (const ch of upper) {
      const glyph = GLYPHS[ch] ?? GLYPHS['?']
      for (let col = 0; col < 5; col++) {
        const bits = glyph[col]
        for (let row = 0; row < 7; row++) {
          if (bits & (1 << row)) {
            ctx.fillRect(cx + col * scale, Math.round(y + dy) + row * scale, scale, scale)
          }
        }
      }
      cx += (5 + tracking) * scale
    }
  }

  if (opts.shadow) render(opts.shadow, scale, scale)
  render(opts.color ?? '#FFF5E4', 0, 0)
}
